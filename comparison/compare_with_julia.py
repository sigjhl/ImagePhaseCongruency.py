def compare_filtergrids(d):
    """Compare filtergrids outputs."""
    results = []
    for rows, cols in [(64, 64), (63, 63), (101, 200), (128, 100)]:
        f_py, fx_py, fy_py = filtergrids(rows, cols)
        results.append(compare(f"filtergrids_{rows}x{cols}_f", load(d, f"filtergrids_{rows}x{cols}_f"), f_py))
        results.append(compare(f"filtergrids_{rows}x{cols}_fx", load(d, f"filtergrids_{rows}x{cols}_fx"), fx_py))
        results.append(compare(f"filtergrids_{rows}x{cols}_fy", load(d, f"filtergrids_{rows}x{cols}_fy"), fy_py))
    return results


def compare_filtergrid(d):
    results = []
    for rows, cols in [(64, 64), (63, 63), (101, 200)]:
        f_py = filtergrid(rows, cols)
        results.append(compare(f"filtergrid_{rows}x{cols}", load(d, f"filtergrid_{rows}x{cols}"), f_py))
    return results


def compare_monogenicfilters(d):
    results = []
    for rows, cols in [(64, 64), (101, 200)]:
        H1, H2, f = monogenicfilters(rows, cols)
        tag = f"monofilters_{rows}x{cols}"
        results.append(compare(f"{tag}_H1_real", load(d, f"{tag}_H1_real"), H1.real))
        results.append(compare(f"{tag}_H1_imag", load(d, f"{tag}_H1_imag"), H1.imag))
        results.append(compare(f"{tag}_H2_real", load(d, f"{tag}_H2_real"), H2.real))
        results.append(compare(f"{tag}_H2_imag", load(d, f"{tag}_H2_imag"), H2.imag))
        results.append(compare(f"{tag}_f", load(d, f"{tag}_f"), f))
    return results


