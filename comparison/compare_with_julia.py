def compare_utilities(d, randimg):
    results = []

    # histtruncate
    results.append(compare("histtruncate_10_10",
                           load(d, "histtruncate_10_10"),
                           histtruncate(randimg, 10.0, 10.0)))
    results.append(compare("histtruncate_5",
                           load(d, "histtruncate_5"),
                           histtruncate(randimg, 5.0)))

    # imgnormalize
    results.append(compare("imgnormalize_01",
                           load(d, "imgnormalize_01"),
                           imgnormalize(randimg)))
    results.append(compare("imgnormalize_mv",
                           load(d, "imgnormalize_mv"),
                           imgnormalize(randimg, 5.0, 2.0)))

    # replacenan
    nanimg = randimg.copy()
    nanimg[9:20, 9:20] = np.nan  # Julia 10:20 is 1-indexed = Python 9:20
    newimg, mask = replacenan(nanimg, 99.0)
    results.append(compare("replacenan_img", load(d, "replacenan_img"), newimg))
    results.append(compare("replacenan_mask", load(d, "replacenan_mask"), mask.astype(np.float64)))

    # hysthresh
    htimg = np.zeros((30, 30))
    htimg[2:25, 14] = 5.0   # Julia 3:25 row, 15 col → Python 2:25, 14
    htimg[7:12, 14] = 10.0  # Julia 8:12 → Python 7:12
    htimg[14:20, 14] = 10.0  # Julia 15:20 → Python 14:20
    htimg[14, 14] = 20.0     # Julia [15,15] → Python [14,14]
    bw = hysthresh(htimg, 8.0, 20.0)
    results.append(compare("hysthresh_result", load(d, "hysthresh_result"), bw.astype(np.float64)))

    # fillnan
    nanimg2 = randimg[:20, :20].copy().astype(np.float64)
    nanimg2[4:10, 4:10] = np.nan  # Julia 5:10 → Python 4:10
    newimg2, mask2 = fillnan(nanimg2)
    results.append(compare("fillnan_img", load(d, "fillnan_img"), newimg2, atol=1e-8, rtol=1e-8))
    results.append(compare("fillnan_mask", load(d, "fillnan_mask"), mask2.astype(np.float64)))

    return results


def compare_phasecongruency_funcs(d, randimg32):
    results = []

    # highpassmonogenic
    ph, orient, E = highpassmonogenic(randimg32, 20.0, 4)
    results.append(compare("highpassmono_phase", load(d, "highpassmono_phase"), ph, atol=1e-8, rtol=1e-8))
    results.append(compare("highpassmono_orient", load(d, "highpassmono_orient"), orient, atol=1e-8, rtol=1e-8))
    results.append(compare("highpassmono_E", load(d, "highpassmono_E"), E, atol=1e-8, rtol=1e-8))

    # bandpassmonogenic
    ph, orient, E = bandpassmonogenic(randimg32, 4.0, 20.0, 4)
    results.append(compare("bandpassmono_phase", load(d, "bandpassmono_phase"), ph, atol=1e-8, rtol=1e-8))
    results.append(compare("bandpassmono_orient", load(d, "bandpassmono_orient"), orient, atol=1e-8, rtol=1e-8))
    results.append(compare("bandpassmono_E", load(d, "bandpassmono_E"), E, atol=1e-8, rtol=1e-8))

    # ppdrc single
    dimg = ppdrc(randimg32 * 100, 20.0, clip=0.01, n=2)
    results.append(compare("ppdrc_single", load(d, "ppdrc_single"), dimg, atol=1e-8, rtol=1e-8))

    # ppdrc multi
    dimgs = ppdrc(randimg32 * 100, geoseries((10.0, 30.0), 3), clip=0.01, n=2)
    jl_count = load(d, "ppdrc_multi_count")
    if jl_count is not None:
        n_expected = int(jl_count[0]) if jl_count.ndim == 1 else int(jl_count)
        if len(dimgs) != n_expected:
            results.append({"name": "ppdrc_multi_count", "status": "FAIL",
                            "reason": f"Count mismatch: Julia {n_expected} vs Python {len(dimgs)}"})
        else:
            results.append({"name": "ppdrc_multi_count", "status": "PASS", "maxdiff": 0.0})
    for i, d_img in enumerate(dimgs):
        results.append(compare(f"ppdrc_multi_{i+1}", load(d, f"ppdrc_multi_{i+1}"), d_img, atol=1e-8, rtol=1e-8))

    # phasecongmono
    PC, or_pcm, ft, T_pcm = phasecongmono(randimg32, nscale=3, minwavelength=3, mult=2.0,
                                            sigmaonf=0.55, k=3.0, noisemethod=-1.0,
                                            cutoff=0.5, g=10.0, deviationgain=1.5)
    results.append(compare("phasecongmono_PC", load(d, "phasecongmono_PC"), PC, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecongmono_or", load(d, "phasecongmono_or"), or_pcm, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecongmono_ft", load(d, "phasecongmono_ft"), ft, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecongmono_T", load(d, "phasecongmono_T"), np.atleast_1d(T_pcm), atol=1e-8, rtol=1e-8))

    # phasesymmono
    phSym, symE, T_psm = phasesymmono(randimg32, nscale=3, minwavelength=3, mult=2.0,
                                        sigmaonf=0.55, k=2.0, polarity=0, noisemethod=-1.0)
    results.append(compare("phasesymmono_phSym", load(d, "phasesymmono_phSym"), phSym, atol=1e-8, rtol=1e-8))
    results.append(compare("phasesymmono_symE", load(d, "phasesymmono_symE"), symE, atol=1e-8, rtol=1e-8))
    results.append(compare("phasesymmono_T", load(d, "phasesymmono_T"), np.atleast_1d(T_psm), atol=1e-8, rtol=1e-8))

    # phasecong3
    M, m, or_pc3, featType, EO, T_pc3 = phasecong3(randimg32, nscale=3, norient=4,
                                                      minwavelength=3, mult=2.0,
                                                      sigmaonf=0.55, k=2.0,
                                                      cutoff=0.5, g=10.0, noisemethod=-1.0)
    jl_M = load(d, "phasecong3_Mmax")
    if jl_M is None:
        jl_M = load(d, "phasecong3_M")
    jl_m = load(d, "phasecong3_mmin")
    if jl_m is None:
        jl_m = load(d, "phasecong3_m")
    results.append(compare("phasecong3_M", jl_M, M, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_m", jl_m, m, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_or", load(d, "phasecong3_or"), or_pc3, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_ft", load(d, "phasecong3_ft"), featType, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_T", load(d, "phasecong3_T"), np.atleast_1d(T_pc3), atol=1e-8, rtol=1e-8))

    # EO slices
    results.append(compare("phasecong3_EO_1_1_real", load(d, "phasecong3_EO_1_1_real"),
                           EO[0][0].real, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_EO_1_1_imag", load(d, "phasecong3_EO_1_1_imag"),
                           EO[0][0].imag, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_EO_2_3_real", load(d, "phasecong3_EO_2_3_real"),
                           EO[1][2].real, atol=1e-8, rtol=1e-8))
    results.append(compare("phasecong3_EO_2_3_imag", load(d, "phasecong3_EO_2_3_imag"),
                           EO[1][2].imag, atol=1e-8, rtol=1e-8))

    # phasesym
    phSym2, orient2, totE, T_ps = phasesym(randimg32, nscale=3, norient=4,
                                             minwavelength=3, mult=2.0, sigmaonf=0.55,
                                             k=2.0, polarity=0, noisemethod=-1.0)
    results.append(compare("phasesym_phSym", load(d, "phasesym_phSym"), phSym2, atol=1e-8, rtol=1e-8))
    results.append(compare("phasesym_orient", load(d, "phasesym_orient"), orient2, atol=1e-8, rtol=1e-8))
    results.append(compare("phasesym_totE", load(d, "phasesym_totE"), totE, atol=1e-8, rtol=1e-8))
    results.append(compare("phasesym_T", load(d, "phasesym_T"), np.atleast_1d(T_ps), atol=1e-8, rtol=1e-8))

    # ppdenoise
    clean = ppdenoise(randimg32, nscale=3, norient=4, mult=2.5,
                       minwavelength=2, sigmaonf=0.55,
                       dthetaonsigma=1.0, k=3.0, softness=1.0)
    results.append(compare("ppdenoise_clean", load(d, "ppdenoise_clean"), clean, atol=1e-8, rtol=1e-8))

    # monofilt
    f_mf, h1f_mf, h2f_mf, A_mf, theta_mf, psi_mf = monofilt(randimg32, 3, 3, 2.0, 0.55, False)
    for s in range(3):
        results.append(compare(f"monofilt_f_{s+1}", load(d, f"monofilt_f_{s+1}"), f_mf[s], atol=1e-8, rtol=1e-8))
        results.append(compare(f"monofilt_h1f_{s+1}", load(d, f"monofilt_h1f_{s+1}"), h1f_mf[s], atol=1e-8, rtol=1e-8))
        results.append(compare(f"monofilt_h2f_{s+1}", load(d, f"monofilt_h2f_{s+1}"), h2f_mf[s], atol=1e-8, rtol=1e-8))
        results.append(compare(f"monofilt_A_{s+1}", load(d, f"monofilt_A_{s+1}"), A_mf[s], atol=1e-8, rtol=1e-8))
        results.append(compare(f"monofilt_theta_{s+1}", load(d, f"monofilt_theta_{s+1}"), theta_mf[s], atol=1e-8, rtol=1e-8))
        results.append(compare(f"monofilt_psi_{s+1}", load(d, f"monofilt_psi_{s+1}"), psi_mf[s], atol=1e-8, rtol=1e-8))

    # gaborconvolve
    EO_gc, BP_gc = gaborconvolve(randimg32, 3, 4, 3, 2.0, 0.55, 1.3, 0)
    for s in range(3):
        results.append(compare(f"gabor_BP_{s+1}", load(d, f"gabor_BP_{s+1}"), BP_gc[s], atol=1e-8, rtol=1e-8))
        for o in range(4):
            results.append(compare(f"gabor_EO_{s+1}_{o+1}_real",
                                   load(d, f"gabor_EO_{s+1}_{o+1}_real"),
                                   EO_gc[s][o].real, atol=1e-8, rtol=1e-8))
            results.append(compare(f"gabor_EO_{s+1}_{o+1}_imag",
                                   load(d, f"gabor_EO_{s+1}_{o+1}_imag"),
                                   EO_gc[s][o].imag, atol=1e-8, rtol=1e-8))

    return results


