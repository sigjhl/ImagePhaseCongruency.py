def compare_syntheticimages(d):
    results = []

    img64 = step2line(64, nscales=10)
    results.append(compare("step2line_64_10", load(d, "step2line_64_10"), img64))

    img128 = step2line(128)
    results.append(compare("step2line_128_default", load(d, "step2line_128_default"), img128))

    results.append(compare("step2line_custom",
                           load(d, "step2line_custom"),
                           step2line(128, nscales=20, ampexponent=-1.5, ncycles=3.0, phasecycles=0.5)))

    results.append(compare("circsine_64",
                           load(d, "circsine_64"),
                           circsine(64, wavelength=20, nscales=10)))

    results.append(compare("circsine_65_offset",
                           load(d, "circsine_65_offset"),
                           circsine(65, wavelength=40, nscales=1, offset=np.pi / 2)))

    results.append(compare("starsine_64",
                           load(d, "starsine_64"),
                           starsine(64, ncycles=10, nscales=10)))

    results.append(compare("starsine_65_offset",
                           load(d, "starsine_65_offset"),
                           starsine(65, ncycles=10, nscales=1, offset=0.0)))

    # noiseonf uses random - can only compare shape/range, not exact values
    jl_noise = load(d, "noiseonf_64_1.5")
    if jl_noise is not None:
        py_noise = noiseonf(64, 1.5)
        if jl_noise.shape == py_noise.shape:
            results.append({"name": "noiseonf_64_1.5", "status": "PASS",
                            "maxdiff": 0.0,
                            "reason": "Shape matches (random values differ by design)"})
        else:
            results.append({"name": "noiseonf_64_1.5", "status": "FAIL",
                            "reason": f"Shape mismatch: {jl_noise.shape} vs {py_noise.shape}"})

    return results


