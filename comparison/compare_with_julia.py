def load(resultsdir, name):
    """Load a .npy file from the Julia results directory."""
    path = os.path.join(resultsdir, name + ".npy")
    if not os.path.exists(path):
        return None
    return np.load(path)


def compare(name, julia_arr, python_arr, atol=1e-10, rtol=1e-10):
    """Compare two arrays and return a result dict."""
    if julia_arr is None:
        return {"name": name, "status": "SKIP", "reason": "Julia file not found"}
    if python_arr is None:
        return {"name": name, "status": "SKIP", "reason": "Python result is None"}

    julia_arr = np.asarray(julia_arr, dtype=np.float64)
    python_arr = np.asarray(python_arr, dtype=np.float64)

    if julia_arr.shape != python_arr.shape:
        return {
            "name": name,
            "status": "FAIL",
            "reason": f"Shape mismatch: Julia {julia_arr.shape} vs Python {python_arr.shape}",
        }

    # Handle NaN: both NaN in same position is OK
    julia_nan = np.isnan(julia_arr)
    python_nan = np.isnan(python_arr)
    if not np.array_equal(julia_nan, python_nan):
        return {
            "name": name,
            "status": "FAIL",
            "reason": f"NaN positions differ ({julia_nan.sum()} vs {python_nan.sum()} NaNs)",
        }

    # Compare non-NaN values
    mask = ~julia_nan
    if mask.sum() == 0:
        return {"name": name, "status": "PASS", "maxdiff": 0.0}

    diff = np.abs(julia_arr[mask] - python_arr[mask])
    maxdiff = diff.max()
    meandiff = diff.mean()
    close = np.allclose(julia_arr[mask], python_arr[mask], atol=atol, rtol=rtol)

    return {
        "name": name,
        "status": "PASS" if close else "FAIL",
        "maxdiff": maxdiff,
        "meandiff": meandiff,
        "reason": "" if close else f"max diff {maxdiff:.2e}, mean diff {meandiff:.2e}",
    }


