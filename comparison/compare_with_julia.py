def main():
    resultsdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "julia_results")

    if not os.path.isdir(resultsdir):
        print(f"ERROR: Julia results directory not found: {resultsdir}")
        print("Run generate_julia_results.jl first to create reference outputs.")
        sys.exit(1)

    npy_files = [f for f in os.listdir(resultsdir) if f.endswith(".npy")]
    print(f"Found {len(npy_files)} .npy files in {resultsdir}")
    print("=" * 70)

    # Load shared test data
    randimg = load(resultsdir, "randimg_64")
    randimg32 = load(resultsdir, "randimg_32")

    if randimg is None or randimg32 is None:
        print("ERROR: randimg_64.npy or randimg_32.npy not found. Run Julia script first.")
        sys.exit(1)

    all_results = []

    # 1. Frequency filters
    print("\n--- Frequency Filters ---")
    all_results.extend(compare_filtergrids(resultsdir))
    all_results.extend(compare_filtergrid(resultsdir))
    all_results.extend(compare_monogenicfilters(resultsdir))
    all_results.extend(compare_packedmonogenicfilters(resultsdir))
    all_results.extend(compare_lowpassfilter(resultsdir))
    all_results.extend(compare_highpassfilter(resultsdir))
    all_results.extend(compare_bandpassfilter(resultsdir))
    all_results.extend(compare_highboostfilter(resultsdir))
    all_results.extend(compare_loggabor(resultsdir))
    all_results.extend(compare_gridangles(resultsdir))
    all_results.extend(compare_cosineangularfilter(resultsdir))
